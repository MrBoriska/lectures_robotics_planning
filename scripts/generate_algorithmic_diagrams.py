    ensure_dir(filepath)

    start = (30, 160)
    goal = (320, 140)
    poly1 = [(75, 70), (145, 55), (130, 135), (65, 115)]
    poly2 = [(185, 110), (265, 80), (250, 165), (175, 145)]
    polygons = [poly1, poly2]

    all_vertices = [start, goal] + poly1 + poly2
    vis_edges = []
    for i in range(len(all_vertices)):
        for j in range(i + 1, len(all_vertices)):
            u, v = all_vertices[i], all_vertices[j]
            is_poly_edge = False
            for poly in polygons:
                n = len(poly)
                for k in range(n):
                    if (u == poly[k] and v == poly[(k + 1) % n]) or (v == poly[k] and u == poly[(k + 1) % n]):
                        is_poly_edge = True
                        break
            if is_poly_edge or line_of_sight(u, v, polygons):
                vis_edges.append((u, v))

    import heapq
    adj = {v: [] for v in all_vertices}
    for u, v in vis_edges:
        d = dist(u, v)
        adj[u].append((v, d))
        adj[v].append((u, d))

    pq = [(0, start, [start])]
    visited = {}
    shortest_path = []
    min_dist = float('inf')
    while pq:
        d, curr, path = heapq.heappop(pq)
        if curr in visited and visited[curr] <= d:
            continue
        visited[curr] = d
        if curr == goal:
            shortest_path = path
            min_dist = d
            break
        for nxt, weight in adj[curr]:
            if nxt not in visited or d + weight < visited[nxt]:
                heapq.heappush(pq, (d + weight, nxt, path + [nxt]))

    vor_path = [
        start,
        (60, 205),
        (155, 195),
        (215, 205),
        (280, 185),
        goal
    ]
