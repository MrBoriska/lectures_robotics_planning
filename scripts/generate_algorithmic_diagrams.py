def dist(p1, p2):
    return math.hypot(p1[0] - p2[0], p1[1] - p2[1])

def ccw(A, B, C):
    return (C[1] - A[1]) * (B[0] - A[0]) > (B[1] - A[1]) * (C[0] - A[0])

def segments_intersect(A, B, C, D):
    """Check if line segment AB strictly intersects segment CD (excluding shared endpoints)."""
    if A == C or A == D or B == C or B == D:
        return False
    return (ccw(A, C, D) != ccw(B, C, D)) and (ccw(A, B, C) != ccw(A, B, D))

def point_in_polygon(point, poly):
    """Ray casting algorithm for point in polygon."""
    x, y = point
    inside = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if ((y1 > y) != (y2 > y)) and (x < (x2 - x1) * (y - y1) / (y2 - y1) + x1):
            inside = not inside
    return inside

def line_of_sight(p1, p2, polygons):
    """Check line of sight between p1 and p2 against polygonal obstacles."""
    mid = ((p1[0] + p2[0]) / 2, (p1[1] + p2[1]) / 2)
    for poly in polygons:
        if point_in_polygon(mid, poly):
            return False

    for poly in polygons:
        n = len(poly)
        for i in range(n):
            e1 = poly[i]
            e2 = poly[(i + 1) % n]
            if segments_intersect(p1, p2, e1, e2):
                return False
    return True

def convex_hull(points):
    """Monotone chain 2D convex hull algorithm."""
    points = sorted(set(points))
    if len(points) <= 1:
        return points

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower = []
    for p in points:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)

    upper = []
    for p in reversed(points):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)

    return lower[:-1] + upper[:-1]

